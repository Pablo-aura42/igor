class ThemeManager:
    """Хранит список тем и текущую выбранную."""

    def __init__(self, initial="Catppuccin Mocha"):
        self.names = list(THEMES.keys())
        self.current_name = initial if initial in THEMES else self.names[0]

    @property
    def current(self):
        return THEMES[self.current_name]

    def set(self, name):
        if name in THEMES:
            self.current_name = name


# ---------------- Производные цвета для панели меню ----------------
def _add_menu_colors(theme):
    """Дополнить тему цветами для кастомной панели меню."""
    return {
        **theme,
        "menu_bar_bg": theme["bg"],                 # панель того же цвета, что фон окна
        "menu_button_fg": theme["btn_fg"],
        "menu_button_hover": theme["btn_hover"],
        "menu_dropdown_bg": theme["btn_bg"],        # «приподнятая» поверхность
        "menu_dropdown_border": theme["btn_hover"],
        "menu_item_fg": theme["btn_fg"],
        "menu_item_hover": theme["btn_hover"],
    }


# Применяем ко всем темам — так не надо писать 7 новых цветов в каждой
THEMES = {name: _add_menu_colors(t) for name, t in THEMES.items()}
